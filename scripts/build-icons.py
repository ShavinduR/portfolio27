#!/usr/bin/env python3
"""
Icon subset — run with `npm run icons` after using a new Font Awesome icon.

Scans every .html and assets/js/**/*.js file for `fa-<name>` classes, then
writes assets/css/icons.css plus two tiny woff2 fonts containing ONLY those
icons (a few KB instead of ~270 KB for the full set). Run `npm run build:css`
afterwards (`npm run icons` does it for you).

Needs: npm install (Font Awesome Free) and `pip install fonttools brotli`.
"""
import os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FA = os.path.join(ROOT, 'node_modules', '@fortawesome', 'fontawesome-free')
STYLES = {'fa-solid', 'fa-brands', 'fa-regular', 'fas', 'fab', 'far'}

css = open(os.path.join(FA, 'css', 'all.css'), encoding='utf8').read()
brands_css = open(os.path.join(FA, 'css', 'brands.css'), encoding='utf8').read()

used = set()
for root, dirs, files in os.walk(ROOT):
    dirs[:] = [d for d in dirs if d not in ('node_modules', '.git')]
    for f in files:
        if f.endswith('.html') or (f.endswith('.js') and os.sep + 'assets' + os.sep + 'js' in os.path.join(root, f)):
            used |= set(re.findall(r'\bfa-([a-z0-9-]+)', open(os.path.join(root, f), encoding='utf8').read()))
used = {u for u in used if 'fa-' + u not in STYLES}

codes, missing = {}, []
for name in sorted(used):
    m = re.search(r'\.fa-' + re.escape(name) + r'\s*\{\s*--fa:\s*"\\([0-9a-f]+)"', css)
    (codes.__setitem__(name, m.group(1)) if m else missing.append(name))
if missing:
    print('Unknown icons (not in Font Awesome Free 6):', ', '.join(missing))

brands = {n for n in codes if re.search(r'\.fa-' + re.escape(n) + r'\s*\{', brands_css)}
for style, font in (('solid', 'fa-solid-900'), ('brands', 'fa-brands-400')):
    names = [n for n in codes if (n in brands) == (style == 'brands')]
    if not names:
        continue
    subprocess.run([sys.executable, '-m', 'fontTools.subset', os.path.join(FA, 'webfonts', font + '.ttf'),
                    '--unicodes=' + ','.join('U+' + codes[n].upper() for n in names), '--flavor=woff2',
                    '--output-file=' + os.path.join(ROOT, 'assets', 'fonts', font + '-subset.woff2'),
                    '--layout-features=', '--no-hinting'], check=True)

rules = '\n'.join('.fa-%s::before { content: "\\%s"; }' % (n, codes[n]) for n in sorted(codes))
open(os.path.join(ROOT, 'assets', 'css', 'icons.css'), 'w', encoding='utf8').write('''/*
 * AUTO-GENERATED by scripts/build-icons.py (`npm run icons`) — do not edit by hand.
 * Font Awesome Free 6, subset to the %d icons this site uses (icons CC BY 4.0, font SIL OFL 1.1).
 * https://fontawesome.com/license/free
 */
@font-face { font-family: 'FA Solid'; font-style: normal; font-weight: 900; font-display: block;
  src: url('../fonts/fa-solid-900-subset.woff2') format('woff2'); }
@font-face { font-family: 'FA Brands'; font-style: normal; font-weight: 400; font-display: block;
  src: url('../fonts/fa-brands-400-subset.woff2') format('woff2'); }

.fa-solid, .fas, .fa-brands, .fab {
  display: inline-block; font-style: normal; font-variant: normal; line-height: 1;
  text-rendering: auto; -webkit-font-smoothing: antialiased; -moz-osx-font-smoothing: grayscale;
}
.fa-solid, .fas { font-family: 'FA Solid'; font-weight: 900; }
.fa-brands, .fab { font-family: 'FA Brands'; font-weight: 400; }

%s
''' % (len(codes), rules))
print('Icons: %d (%d brand) -> assets/css/icons.css' % (len(codes), len(brands)))
