#!/usr/bin/env node
/**
 * Image pipeline — run with `npm run images`.
 *
 * 1. Finds every .jpg / .jpeg / .png / .jfif under assets/img/
 *    (a .webp added directly is kept as-is and just gets its -800 variant).
 * 2. Writes   <name>.webp       (long edge ≤ 2000px)
 *    and      <name>-800.webp   (width ≤ 800px, used on small screens via srcset)
 *    and      <name>-1200.webp  (only for images wider than 1200px: high-density
 *                                phones pick this instead of the full-size file)
 * 3. Deletes the original (pass --keep to keep it).
 * 4. Rewrites references in *.html and assets/js/**.js from the old
 *    extension to .webp — so you can reference "assets/img/projects/customt.png"
 *    in projects.js, run this, and it just works.
 * 5. Regenerates assets/js/data/images.js — a { path: [width, height] } manifest
 *    used to set width/height (prevents layout shift) and build srcset.
 */
import { readdir, readFile, writeFile, unlink, stat } from 'node:fs/promises';
import { join, extname, relative, sep } from 'node:path';
import sharp from 'sharp';

const ROOT = new URL('..', import.meta.url).pathname;
const IMG_DIR = join(ROOT, 'assets/img');
const KEEP = process.argv.includes('--keep');
const SOURCE = /\.(jpe?g|png|jfif)$/i;
const MAX = 2000;
const SMALL = 800;
const MEDIUM = 1200;
const isVariant = (f) => f.endsWith(`-${SMALL}.webp`) || f.endsWith(`-${MEDIUM}.webp`);

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map((d) => (d.isDirectory() ? walk(join(dir, d.name)) : [join(dir, d.name)]))
  );
  return nested.flat();
}

const posix = (p) => relative(ROOT, p).split(sep).join('/');
const kb = (n) => `${Math.round(n / 1024)} KB`;

async function convert(file) {
  const base = file.slice(0, -extname(file).length);
  const isPng = /\.png$/i.test(file);
  const img = sharp(file, { failOn: 'none' }).rotate(); // honour EXIF orientation
  const meta = await img.metadata();
  // Graphics (PNG) get higher quality to keep text and edges crisp.
  const opts = { quality: isPng ? 88 : 80, alphaQuality: 90, effort: 5, smartSubsample: true };

  await img
    .clone()
    .resize({ width: MAX, height: MAX, fit: 'inside', withoutEnlargement: true })
    .webp(opts)
    .toFile(`${base}.webp`);
  await img
    .clone()
    .resize({ width: SMALL, withoutEnlargement: true })
    .webp(opts)
    .toFile(`${base}-${SMALL}.webp`);
  if (Math.min(meta.width, MAX) > MEDIUM)
    await img.clone().resize({ width: MEDIUM }).webp(opts).toFile(`${base}-${MEDIUM}.webp`);

  const before = (await stat(file)).size;
  const after = (await stat(`${base}.webp`)).size;
  if (!KEEP) await unlink(file);
  console.log(`  ${posix(file)}  ${kb(before)} → ${kb(after)}  (${meta.width}×${meta.height})`);
  return [posix(file), posix(`${base}.webp`), before, after];
}

async function rewriteRefs(map) {
  if (!map.length) return;
  const files = [
    ...(await readdir(ROOT)).filter((f) => f.endsWith('.html')).map((f) => join(ROOT, f)),
    ...(await walk(join(ROOT, 'assets/js'))).filter((f) => f.endsWith('.js')),
  ];
  for (const f of files) {
    let t = await readFile(f, 'utf8');
    const o = t;
    for (const [from, to] of map) t = t.split(from).join(to);
    if (t !== o) {
      await writeFile(f, t);
      console.log(`  updated references in ${posix(f)}`);
    }
  }
}

async function writeManifest() {
  const files = (await walk(IMG_DIR)).filter((f) => f.endsWith('.webp') && !isVariant(f)).sort();
  const entries = await Promise.all(
    files.map(async (f) => {
      const { width, height } = await sharp(f).metadata();
      return `  '${posix(f)}': [${width}, ${height}],`;
    })
  );
  const out = `/* AUTO-GENERATED by scripts/optimize-images.mjs — do not edit by hand. */
window.SITE = window.SITE || {};
window.SITE.images = {
${entries.join('\n')}
};
`;
  await writeFile(join(ROOT, 'assets/js/data/images.js'), out);
  console.log(`\nManifest: ${entries.length} images → assets/js/data/images.js`);
}

// WebP files dropped in directly (or created before a size existed) just need their variants.
const all = await walk(IMG_DIR);
for (const f of all.filter((f) => f.endsWith('.webp') && !isVariant(f))) {
  const small = f.replace(/\.webp$/, `-${SMALL}.webp`);
  if (!all.includes(small)) {
    await sharp(f).resize({ width: SMALL, withoutEnlargement: true }).webp({ quality: 80, effort: 5 }).toFile(small);
    console.log(`  ${posix(f)}  + ${SMALL}px variant`);
  }
  const medium = f.replace(/\.webp$/, `-${MEDIUM}.webp`);
  if (!all.includes(medium) && (await sharp(f).metadata()).width > MEDIUM) {
    await sharp(f).resize({ width: MEDIUM }).webp({ quality: 80, effort: 5 }).toFile(medium);
    console.log(`  ${posix(f)}  + ${MEDIUM}px variant`);
  }
}

const sources = all.filter((f) => SOURCE.test(f));
console.log(sources.length ? `Optimising ${sources.length} image(s)…` : 'No new images to optimise.');
const results = [];
for (const f of sources) results.push(await convert(f));
if (results.length) {
  const [b, a] = results.reduce(([b, a], r) => [b + r[2], a + r[3]], [0, 0]);
  console.log(`\nTotal: ${kb(b)} → ${kb(a)} (−${Math.round((1 - a / b) * 100)}%)`);
}
await rewriteRefs(results.map(([from, to]) => [from, to]));
await writeManifest();
